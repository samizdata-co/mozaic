// Builds src/lib/flags/svgs.ts from the square flags of flag-icons (MIT).
// Run from packages/mozaic after updating the flag-icons devDependency:
//   node scripts/build-flags.js
//
// Each flag becomes a named export (upper-case ISO 3166-1 alpha-2 code, plus EU and UN)
// holding the flag's inner SVG markup on a 512 × 512 viewBox. Ids are prefixed so flags
// can sit inline in any page. Eurostat's EL (Greece) and UK (United Kingdom) are aliases.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const pkgPath = require.resolve('flag-icons/package.json');
const { version } = JSON.parse(readFileSync(pkgPath, 'utf8'));
const dir = join(dirname(pkgPath), 'flags', '1x1');

const aliases = { EL: 'GR', UK: 'GB' };

/** Inner markup of one flag file, minified, with ids prefixed. */
function inner(svg) {
	const body = svg
		.replace(/^[\s\S]*?<svg[^>]*>/, '')
		.replace(/<\/svg>\s*$/, '')
		.replace(/>\s+</g, '><')
		.replace(/\s+/g, ' ')
		.trim();
	return body
		.replace(/\bid="([^"]+)"/g, 'id="mz-flag-$1"')
		.replace(/url\(#([^)]+)\)/g, 'url(#mz-flag-$1)')
		.replace(/href="#([^"]+)"/g, 'href="#mz-flag-$1"');
}

const files = readdirSync(dir)
	.filter((f) => /^([a-z]{2}|eu|un)\.svg$/.test(f))
	.sort();

const lines = [
	'// Generated by scripts/build-flags.js. Do not edit.',
	`// Flags from flag-icons ${version} (https://github.com/lipis/flag-icons),`,
	'// MIT License, Copyright (c) 2013 Panayiotis Lipiridis.',
	'// Inner SVG markup of each square flag, on a 512 × 512 viewBox.',
	''
];
for (const f of files) {
	const code = f.replace('.svg', '').toUpperCase();
	const markup = inner(readFileSync(join(dir, f), 'utf8'))
		.replace(/\\/g, '\\\\')
		.replace(/'/g, "\\'");
	lines.push(`export const ${code} = '${markup}';`);
}
lines.push('');
for (const [alias, code] of Object.entries(aliases)) {
	lines.push(`/** Eurostat code for ${code === 'GR' ? 'Greece' : 'the United Kingdom'}. */`);
	lines.push(`export const ${alias} = ${code};`);
}
lines.push('');

const out = new URL('../src/lib/flags/svgs.ts', import.meta.url);
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${files.length} flags and ${Object.keys(aliases).length} aliases to ${out.pathname}`);
